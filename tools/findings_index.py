#!/usr/bin/env python3
"""Generate the finding index from Markdown metadata, with no third-party deps."""
import argparse
import os
from pathlib import Path
import re
import sys


def locate_findings():
    workspace = os.environ.get("BUILD_WORKSPACE_DIRECTORY")
    candidates = [Path(workspace) / "findings"] if workspace else []
    candidates += [Path(__file__).resolve().parent.parent / "findings", Path.cwd() / "findings"]
    for candidate in candidates:
        if (candidate / "TEMPLATE.md").is_file():
            return candidate
    raise SystemExit("Cannot locate findings directory")


def cell(value):
    return value.replace("|", "\\|").replace("\n", " ")


def generate(directory):
    lines = ["# Findings index", "", "<!-- Generated by tools/findings_index. Do not edit. -->", "",
             "| Finding | Components | Severity | Status | Repro target |",
             "| --- | --- | --- | --- | --- |"]
    count = 0
    for path in sorted(directory.glob("*.md")):
        if path.name in {"TEMPLATE.md", "README.md", "INDEX.md"}:
            continue
        fields = {}
        for line in path.read_text().splitlines():
            match = re.match(r"^([A-Za-z ()/]+):\s*(.*)$", line)
            if match:
                fields[match.group(1)] = match.group(2).strip()
        required = ["Title", "Components", "Image version/digest", "Severity", "Severity justification",
                    "Status", "Repro test target", "BuildBuddy invocation"]
        missing = [field for field in required if not fields.get(field)]
        if missing:
            raise ValueError(f"{path.name}: missing metadata: {', '.join(missing)}")
        if fields["Status"] not in {"unverified", "confirmed", "rejected"}:
            raise ValueError(f"{path.name}: invalid status")
        if fields["Severity"] not in {"critical", "high", "medium", "low"}:
            raise ValueError(f"{path.name}: invalid severity")
        title = cell(fields["Title"]).replace("[", "\\[").replace("]", "\\]")
        lines.append(f"| [{title}]({path.name}) | {cell(fields['Components'])} | "
                     f"{fields['Severity']} | {fields['Status']} | `{cell(fields['Repro test target'])}` |")
        count += 1
    if count == 0:
        lines += ["", "No findings recorded."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = locate_findings()
    try:
        generated = generate(directory)
    except ValueError as error:
        raise SystemExit(str(error))
    index = directory / "INDEX.md"
    if args.check:
        if not index.exists() or index.read_text() != generated:
            raise SystemExit("findings/INDEX.md is stale; run tools/findings_index")
    else:
        index.write_text(generated)


if __name__ == "__main__":
    main()
